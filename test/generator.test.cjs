const test = require('node:test');
const assert = require('node:assert/strict');
const { parse } = require('yaml');
const { analyzeWorkflow } = require('../dist-test/core/analyzer.js');
const {
  generateCI, GeneratorOptionsError, PRESETS, PRESET_REQUIREMENTS, missingMarkers,
} = require('../dist-test/core/generator.js');

const SHA = 'a'.repeat(40);
const pins = { uploadArtifact: SHA, cache: SHA, dependencyReview: SHA, codeqlAction: SHA };
const errorsOf = (yaml) => analyzeWorkflow(yaml).findings.filter((f) => f.severity === 'error');
const usesOf = (yaml) => {
  const doc = parse(yaml);
  return Object.values(doc.jobs).flatMap((job) => (job.steps ?? []).map((s) => s.uses).filter(Boolean));
};
const throwsOptions = (options, field) => {
  assert.throws(() => generateCI(options), (e) => e instanceof GeneratorOptionsError &&
    (field === undefined || e.issues.some((i) => i.field === field)), field);
};

test('every preset has requirements data (single source of truth)', () => {
  for (const preset of PRESETS.filter((p) => p !== 'maven')) {
    assert.ok(PRESET_REQUIREMENTS[preset].markers.length > 0, preset);
    assert.ok(PRESET_REQUIREMENTS[preset].needsRealExecution.length > 0, preset);
  }
  assert.deepEqual(missingMarkers('go', ['go.mod']), []);
  assert.deepEqual(missingMarkers('maven', []), [['pom.xml']]);
});

for (const preset of PRESETS) {
  test('preset ' + preset + ' generates clean, pinned, least-privilege YAML', () => {
    const yaml = generateCI({ preset, trigger: 'push-and-pr' });
    const doc = parse(yaml);
    assert.equal(analyzeWorkflow(yaml).syntaxValid, true);
    assert.deepEqual(errorsOf(yaml), []);
    assert.deepEqual(analyzeWorkflow(yaml).findings, []);
    assert.deepEqual(doc.permissions, { contents: 'read' });
    assert.ok(doc.concurrency['cancel-in-progress']);
    assert.ok(yaml.startsWith('# Generated by Orquestivo'));
    assert.ok(yaml.includes('# Static validation is not evidence'));
    for (const job of Object.values(doc.jobs)) assert.equal(typeof job['timeout-minutes'], 'number');
    for (const uses of usesOf(yaml)) assert.match(uses, /@[0-9a-f]{40}$/);
  });
}

test('maven alias renders like java-maven', () => {
  assert.equal(generateCI({ preset: 'maven' }), generateCI({ preset: 'java-maven' }));
});

test('legacy flow triggers are preserved', () => {
  assert.ok(generateCI({ preset: 'node', trigger: 'pr-only' }).includes('on: [pull_request]\n'));
  assert.ok(generateCI({ preset: 'node', trigger: 'push-and-pr' }).includes('on: [push, pull_request]\n'));
});

test('node package managers pick install, cache and Corepack', () => {
  const pnpm = parse(generateCI({ preset: 'node', packageManager: 'pnpm' }));
  const steps = pnpm.jobs.verify.steps;
  assert.equal(steps[1].run, 'corepack enable');
  assert.equal(steps[2].with.cache, 'pnpm');
  assert.ok(steps.some((s) => s.run === 'pnpm install --frozen-lockfile'));
  const yarn = generateCI({ preset: 'react', packageManager: 'yarn' });
  assert.ok(yarn.includes('yarn install --immutable') && yarn.includes('yarn run build'));
  const npm = generateCI({ preset: 'node' });
  assert.ok(npm.includes('run: npm ci') && !npm.includes('corepack'));
});

test('typescript type-checks by default; next builds and notes the missing cache pin', () => {
  assert.ok(generateCI({ preset: 'typescript' }).includes('npx --no-install tsc --noEmit'));
  const noPin = generateCI({ preset: 'next' });
  assert.ok(noPin.includes('run: npm run build') && noPin.includes('# Note: .next/cache is not cached'));
  const withPin = generateCI({ preset: 'next', actionPins: pins });
  assert.ok(withPin.includes('actions/cache@' + SHA) && withPin.includes('.next/cache'));
  assert.deepEqual(errorsOf(withPin), []);
});

test('detailed triggers, branches, schedule and dispatch', () => {
  const yaml = generateCI({ preset: 'go', triggers: { push: true, pullRequest: true, branches: ['main', 'release/*'], schedule: '0 3 * * 1', manualDispatch: true } });
  const on = parse(yaml).on;
  assert.deepEqual(on.push.branches, ['main', 'release/*']);
  assert.deepEqual(on.pull_request.branches, ['main', 'release/*']);
  assert.deepEqual(on.schedule, [{ cron: '0 3 * * 1' }]);
  assert.ok('workflow_dispatch' in on);
  assert.deepEqual(errorsOf(yaml), []);
});

test('OS and runtime matrix', () => {
  const yaml = generateCI({
    preset: 'node', operatingSystems: ['ubuntu', 'windows', 'macos'], runtimeVersions: ['20', '22'],
    artifacts: { path: 'dist', retentionDays: 7 }, actionPins: pins,
  });
  const job = parse(yaml).jobs.verify;
  assert.deepEqual(job.strategy.matrix.os, ['ubuntu-latest', 'windows-latest', 'macos-latest']);
  assert.deepEqual(job.strategy.matrix.runtime, ['20', '22']);
  assert.equal(job.strategy['fail-fast'], false);
  assert.equal(job.defaults.run.shell, 'bash');
  assert.equal(job['runs-on'], '${{ matrix.os }}');
  assert.equal(job.steps[1].with['node-version'], '${{ matrix.runtime }}');
  const upload = job.steps.at(-1);
  assert.equal(upload.with['retention-days'], 7);
  assert.equal(upload.with.name, 'build-${{ matrix.os }}-${{ matrix.runtime }}');
  assert.deepEqual(errorsOf(yaml), []);
});

test('lint, build and test toggles', () => {
  const yaml = generateCI({ preset: 'go', lint: true, build: true, test: false });
  assert.ok(yaml.includes('go vet ./...') && yaml.includes('go build ./...') && !yaml.includes('go test'));
  const gradle = generateCI({ preset: 'java-gradle', build: true });
  assert.ok(gradle.includes('assemble') && gradle.includes('gradlew --no-daemon test') && gradle.includes('cache: gradle'));
  assert.ok(generateCI({ preset: 'go', cache: false }).includes('cache: false'));
});

test('docker builds with buildx and never pushes', () => {
  const yaml = generateCI({ preset: 'docker' });
  assert.ok(yaml.includes('docker buildx build --load'));
  assert.ok(!yaml.includes('docker push') && !yaml.includes('--push'));
});

test('php uses composer without third-party setup actions', () => {
  const yaml = generateCI({ preset: 'php', lint: true });
  assert.ok(yaml.includes('composer validate --strict') && yaml.includes('vendor/bin/phpunit'));
  assert.deepEqual(usesOf(yaml).filter((u) => !u.startsWith('actions/checkout@')), []);
});

test('security scans live in a separate least-privilege job', () => {
  const audit = parse(generateCI({ preset: 'node', packageManager: 'pnpm', securityScan: 'audit', sequentialJobs: true }));
  assert.equal(audit.jobs.security.needs[0], 'verify');
  assert.deepEqual(audit.jobs.security.permissions, { contents: 'read' });
  assert.ok(audit.jobs.security.steps.some((s) => s.run === 'pnpm audit --audit-level high'));
  const composer = generateCI({ preset: 'php', securityScan: 'audit' });
  assert.ok(composer.includes('composer audit'));

  const review = generateCI({ preset: 'node', securityScan: 'dependency-review', actionPins: pins });
  assert.ok(review.includes("if: github.event_name == 'pull_request'"));
  assert.deepEqual(errorsOf(review), []);

  const codeql = parse(generateCI({ preset: 'go', securityScan: 'codeql', actionPins: pins }));
  assert.equal(codeql.jobs.security.permissions['security-events'], 'write');
  assert.deepEqual(codeql.jobs.security.steps.map((s) => s.name), ['Check out source', 'Initialize CodeQL', 'Autobuild', 'Analyze']);
  assert.equal(codeql.permissions['security-events'], undefined);
});

test('deploy job is gated, scoped and fails closed', () => {
  const yaml = generateCI({
    preset: 'node', triggers: { push: true, pullRequest: true }, securityScan: 'audit',
    deploy: { environment: 'production' },
  });
  const doc = parse(yaml);
  const deploy = doc.jobs.deploy;
  assert.deepEqual(deploy.needs, ['verify', 'security']);
  assert.equal(deploy.environment, 'production');
  assert.equal(deploy.permissions['id-token'], 'write');
  assert.equal(deploy.if, "github.ref == 'refs/heads/main' && github.event_name != 'pull_request'");
  assert.equal(deploy.concurrency['cancel-in-progress'], false);
  assert.ok(deploy.steps.at(-1).run.trim().endsWith('exit 1'));
  assert.equal(doc.permissions['id-token'], undefined);
  assert.equal(doc.jobs.verify.permissions, undefined);
  assert.deepEqual(errorsOf(yaml), []);
  assert.ok(!yaml.includes('curl') && !yaml.includes('aws '));
});

test('invalid option combinations throw GeneratorOptionsError', () => {
  throwsOptions({ preset: 'nope' }, 'preset');
  throwsOptions({ preset: 'node', trigger: 'pr-only', triggers: { push: true } }, 'triggers');
  throwsOptions({ preset: 'node', triggers: {} }, 'triggers');
  throwsOptions({ preset: 'node', triggers: { push: true, branches: ['a b'] } }, 'triggers');
  throwsOptions({ preset: 'node', triggers: { manualDispatch: true, branches: ['main'] } }, 'triggers');
  throwsOptions({ preset: 'node', triggers: { schedule: 'every day' } }, 'triggers');
  throwsOptions({ preset: 'go', packageManager: 'pnpm' }, 'packageManager');
  throwsOptions({ preset: 'docker', operatingSystems: ['windows'] }, 'operatingSystems');
  throwsOptions({ preset: 'node', operatingSystems: [] }, 'operatingSystems');
  throwsOptions({ preset: 'node', operatingSystems: ['ubuntu', 'ubuntu'] }, 'operatingSystems');
  throwsOptions({ preset: 'php', runtimeVersions: ['8.3'] }, 'runtimeVersions');
  throwsOptions({ preset: 'node', runtimeVersions: ['22; rm -rf'] }, 'runtimeVersions');
  throwsOptions({ preset: 'docker', test: true }, 'test');
  throwsOptions({ preset: 'maven', lint: true }, 'lint');
  throwsOptions({ preset: 'docker', build: false }, 'test');
  throwsOptions({ preset: 'go', securityScan: 'audit' }, 'securityScan');
  throwsOptions({ preset: 'php', securityScan: 'codeql', actionPins: pins }, 'securityScan');
  throwsOptions({ preset: 'node', securityScan: 'codeql' }, 'actionPins.codeqlAction');
  throwsOptions({ preset: 'node', securityScan: 'dependency-review', trigger: 'pr-only' }, 'actionPins.dependencyReview');
  throwsOptions({ preset: 'node', securityScan: 'dependency-review', actionPins: pins, triggers: { push: true } }, 'securityScan');
  throwsOptions({ preset: 'node', artifacts: { path: 'dist' } }, 'actionPins.uploadArtifact');
  throwsOptions({ preset: 'node', artifacts: { path: '../x' }, actionPins: pins }, 'artifacts.path');
  throwsOptions({ preset: 'node', artifacts: { path: 'dist', retentionDays: 400 }, actionPins: pins }, 'artifacts.retentionDays');
  throwsOptions({ preset: 'node', actionPins: { cache: 'v4' } }, 'actionPins.cache');
  throwsOptions({ preset: 'node', deploy: { environment: 'prod uction' } }, 'deploy.environment');
  throwsOptions({ preset: 'node', deploy: { environment: 'prod', branch: 'rel/*' } }, 'deploy.branch');
  throwsOptions({ preset: 'node', trigger: 'pr-only', deploy: { environment: 'prod' } }, 'deploy');
});

test('errors collect every issue', () => {
  try {
    generateCI({ preset: 'docker', test: true, operatingSystems: ['macos'] });
    assert.fail('expected throw');
  } catch (e) {
    assert.ok(e instanceof GeneratorOptionsError);
    assert.ok(e.issues.length >= 2);
    assert.equal(e.name, 'GeneratorOptionsError');
  }
});
