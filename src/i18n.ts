export type TextKey = keyof typeof en;
export type Params = Readonly<Record<string, string | number>>;
export type Translate = (key: TextKey, params?: Params) => string;
export type Language = 'en' | 'es';

/** Both catalogs, exposed for tests and tooling. */
export const messages: Readonly<Record<Language, Readonly<Record<TextKey, string>>>> = { en, es };

export function resolveLanguage(language: string): Language {
  return language.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function tr(key: TextKey, language: string, params?: Params): string {
  const template = messages[resolveLanguage(language)][key];
  return params ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : template;
}
