/** Auditable, read-only CI templates. They do not deploy software or prove success. */
export type Preset = 'node' | 'go' | 'python' | 'maven';
export type Trigger = 'push-and-pr' | 'pr-only';
export interface GeneratorOptions { readonly preset: Preset; readonly trigger: Trigger; }

const checkout = 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1'; // v7
const setupNode = 'actions/setup-node@249970729cb0ef3589644e2896645e5dc5ba9c38'; // v6
const setupGo = 'actions/setup-go@924ae3a1cded613372ab5595356fb5720e22ba16'; // v6
const setupPython = 'actions/setup-python@ece7cb06caefa5fff74198d8649806c4678c61a1'; // v6
const setupJava = 'actions/setup-java@b843ebf9b913146b38da2eaa7aeddf76074ae1ad'; // v6

function steps(preset: Preset): readonly string[] {
  switch (preset) {
    case 'node': return [
      '      - name: Set up Node.js',
      '        uses: ' + setupNode,
      '        with:', '          node-version: "22"', '          cache: npm',
      '      - name: Install locked dependencies', '        run: npm ci',
      '      - name: Run project tests', '        run: npm test',
    ];
    case 'go': return [
      '      - name: Set up Go', '        uses: ' + setupGo,
      '        with:', '          go-version-file: go.mod',
      '      - name: Run project tests', '        run: go test ./...',
    ];
    case 'python': return [
      '      - name: Set up Python', '        uses: ' + setupPython,
      '        with:', '          python-version: "3.12"',
      '      - name: Install test dependencies', '        run: |',
      '          python -m pip install --upgrade pip pytest',
      '          if [ -f requirements.txt ]; then python -m pip install -r requirements.txt; fi',
      '      - name: Run project tests', '        run: python -m pytest',
    ];
    case 'maven': return [
      '      - name: Set up Java', '        uses: ' + setupJava,
      '        with:', '          distribution: temurin', '          java-version: "21"', '          cache: maven',
      '      - name: Verify Maven project', '        run: mvn --batch-mode verify',
    ];
  }
}

export function generateCI(options: GeneratorOptions): string {
  const triggers = options.trigger === 'pr-only'
    ? 'on: [pull_request]' : 'on: [push, pull_request]';
  const group = '  group: ' + "'$" + '{{ github.workflow }}-$' + "{{ github.ref }}'";
  return [
    '# Generated by Orquestivo — review before committing.',
    '# Static validation is not evidence that CI will pass.',
    'name: CI', triggers, '',
    'permissions:', '  contents: read', '',
    'concurrency:', group, '  cancel-in-progress: true', '',
    'jobs:', '  verify:', '    name: Verify',
    '    runs-on: ubuntu-latest', '    timeout-minutes: 20', '    steps:',
    '      - name: Check out source', '        uses: ' + checkout,
    ...steps(options.preset), '',
  ].join('\n');
}
